def parse_dft_reports(root):
    reports = root / "reports"
    result = {"project_root": str(root), "reports_dir": str(reports), "status": "unknown", "checks": {}}
    for name in ("dft_pre.rpt", "dft_post.rpt"):
        p = reports / name
        if not p.exists(): continue
        text = p.read_text(errors="replace")
        m = re.search(r"Total violations:\s*(\d+)", text)
        cells = re.search(r"\*\s+(\d+) cells are valid scan cells", text)
        result["checks"][name] = {"total_violations": int(m.group(1)) if m else None,
                                   "valid_scan_cells": int(cells.group(1)) if cells else None}
    p = reports / "scan_chain.rpt"
    if p.exists():
        text = p.read_text(errors="replace")
        rows = re.findall(r"^I\s+(\d+)\s+(\d+)\s+\S+\s+\S+\s+\S+", text, re.M)
        result["scan_chains"] = [{"chain": int(a), "length": int(b)} for a,b in rows]
    p = reports / "dft_qor.rpt"
    if p.exists():
        text = p.read_text(errors="replace")
        def num(label):
            m = re.search(re.escape(label) + r":\s*([-+]?\d+(?:\.\d+)?)", text)
            return float(m.group(1)) if m else None
        result["qor"] = {"cell_area": num("Cell Area"), "wns": num("Design  WNS"), "tns": num("Design  TNS")}
    violations = [v["total_violations"] for v in result["checks"].values() if v.get("total_violations") is not None]
    if len(violations) == 2 and all(v == 0 for v in violations): result["status"] = "pass"
    elif any(v != 0 for v in violations): result["status"] = "fail"
    else: result["status"] = "blocked"
    return result

def discover_top(root, configured=None):
    if configured and not configured.lower().startswith(("tb_", "test_", "testbench")):
        return configured
    modules = []
    for src in rtl_sources(root):
        try: modules += re.findall(r"\bmodule\s+([A-Za-z_][\w$]*)", Path(src).read_text(errors="replace"))
        except OSError: pass
    non_tb = [m for m in modules if not m.lower().startswith(("tb_", "test_", "testbench"))]
    return (non_tb or modules or [root.name])[0]

def latest_artifact(root, names):
    candidates = []
    for base in (root / "runs", root):
        for name in names: candidates += [p for p in base.glob("**/" + name) if p.is_file()]
    return str(max(candidates, key=lambda p: p.stat().st_mtime)) if candidates else None

def executable(tool):
    env_name, name = HOME_DEFAULTS[tool]
    home = os.environ.get(env_name)
    candidate = Path(home) / "bin" / name if home else None
    return str(candidate) if candidate and candidate.is_file() and os.access(candidate, os.X_OK) else shutil.which(name)

def ensure_config(root):
    path = root / "eda.yaml"
    if not path.exists():
        raise ConfigError("eda.yaml is missing; use the explicit 'init' command and review the generated paths")
    return path

def rtl_sources(root):
    config = root / "eda.yaml"
    if config.exists():
        return sources(root, load(config))["rtl"]
    return []

def tcl_header(flow):
    return f"# Generated by eda-tool-engineering ({flow}); edit eda.yaml, not this file.\n"

def yaml_scalar(path, key, default=None):
    """Read simple scalar/nested values from the dependency-free contract parser."""
    if not path.exists(): return default
    lines = path.read_text(errors="replace").splitlines()
    for i, raw in enumerate(lines):
        line = raw.split("#", 1)[0].rstrip()
        m = re.match(r"^(\s*)" + re.escape(key) + r":\s*(.*?)\s*$", line)
        if not m: continue
        value = m.group(2).strip().strip("'\"")
        if value: return value
        # A nested mapping's first scalar is not a value for this key.
    return default

def dft_paths(root, cfg):
    cfg_path = root / "eda.yaml"
    netlist = yaml_scalar(cfg_path, "scan_netlist") or "netlist/tsmc28_smoke_scan.v"
    spf = yaml_scalar(cfg_path, "test_protocol") or "dft/tsmc28_smoke.spf"
    library = yaml_scalar(cfg_path, "library_verilog")
    if not library:
        hits = list(root.glob("**/*_Front_End*/verilog/*.v")) + list(root.glob("**/digital/**/*.v"))
        library = str(hits[0]) if hits else ""
    return netlist, spf, library

def write_atpg_script(path, top, netlist, spf, library, model):
    delay = "\nset_delay -launch system" if model == "transition" else ""
    libline = f"read_netlist -library {{{library}}}" if library else "# TODO: set library_verilog in eda.yaml"
    path.write_text("\n".join([
        f"# Generated TestMAX ATPG script ({model})", "set_commands noabort",
        f"set_messages -log ./logs/{model}_internal.log -replace", libline,
        f"read_netlist {{{netlist}}}", f"run_build_model {top}",
        f"set_drc {{{spf}}}", "run_drc", "report_rules -fail",
        f"set_faults -model {('stuck' if model == 'stuck_at' else model)}", delay,
        "add_faults -all", "run_atpg -auto", "report_faults -summary",
        f"write_patterns ./patterns/{top}_{model}.stil -format STIL -replace",
        "exit -force", ""
    ]))

def atpg_metrics(root):
    metrics = {}
    for p in list((root / "atpg").glob("**/*")) + list((root / "runs").glob("**/*")):
        if not p.is_file() or p.suffix not in (".rpt", ".log"): continue
        text = p.read_text(errors="replace")
        for label, key in (("Detected Faults", "detected_faults"), ("Undetected Faults", "undetected_faults"), ("Aborted Faults", "aborted_faults"), ("Total Patterns", "patterns")):
            m = re.search(re.escape(label) + r"\s*[:=]?\s*(\d+)", text, re.I)
            if m: metrics[key] = int(m.group(1))
        m = re.search(r"(?:fault|test)\s+coverage\s*[:=]?\s*([0-9]+(?:\.\d+)?)\s*%", text, re.I)
        if m: metrics["coverage_percent"] = float(m.group(1))
    return metrics

def generate_dft_manager(root, cfg, run_dir, flow):
    top = discover_top(root, cfg.get("top")); netlist, spf, library = dft_paths(root, cfg)
    if flow == "atpg":
        netlist = yaml_scalar(root / "eda.yaml", "scan_netlist") or latest_artifact(root, ["dft_netlist.v", "*_scan.v"]) or netlist
        spf = yaml_scalar(root / "eda.yaml", "test_protocol") or latest_artifact(root, ["design.spf", "*.spf"]) or spf
    rtl = rtl_sources(root)
    # Scan insertion is a DC DFT flow; TestMAX tmax consumes its SPF/netlist for ATPG.
    scan = run_dir / "scan_insert.tcl"
    rtl_list = " ".join("{" + x + "}" for x in rtl)
    scan.write_text("\n".join([
        tcl_header("dft-scan"), f"set TOP {top}", f"set RUN {{{run_dir}}}",
        f"set TARGET_DB {{{os.environ.get('TSMC28_STD_TT', '')}}}",
        "if {$TARGET_DB ne \"\"} { set_app_var target_library [list $TARGET_DB]; set_app_var link_library [list \"*\" $TARGET_DB] }",
        f"read_verilog -rtl [list {rtl_list}]", "current_design $TOP", "link", "compile -scan",
        "# Configure these ports/clocks in eda.yaml before execution.",
        "set_dft_signal -view existing_dft -type ScanClock -port clk -timing {45 55}",
        "set_dft_signal -view existing_dft -type Reset -port rst_n -active_state 0",
        "set_dft_signal -view spec -type ScanDataIn -port scan_in",
        "set_dft_signal -view spec -type ScanDataOut -port scan_out",
        "set_dft_signal -view spec -type ScanEnable -port scan_en -active_state 1",
        "set_scan_configuration -style multiplexed_flip_flop -chain_count 1",
        "create_test_protocol", "dft_drc -verbose > $RUN/dft_pre.rpt", "preview_dft -show all > $RUN/preview_dft.rpt",
        "insert_dft", "dft_drc -verbose > $RUN/dft_post.rpt",
        "report_scan_path -view existing_dft -chain all > $RUN/scan_chain.rpt",
        "report_scan_path -view existing_dft -cell all > $RUN/scan_cells.rpt",
        "report_dft_signal -view existing_dft -port * > $RUN/dft_signals.rpt",
        f"write -format verilog -hierarchy -output {{{run_dir}/dft_netlist.v}}",
        f"write_test_protocol -output {{{run_dir}/design.spf}}", "exit", ""
    ]))
    artifacts = [str(scan)]
    if flow in ("dft", "atpg"):
        for model in ("stuck_at", "transition"):
            p = run_dir / f"atpg_{model}.cmd"; write_atpg_script(p, top, netlist, spf, library, model); artifacts.append(str(p))
    if flow in ("dft", "mbist"):
        p = run_dir / "mbist.tcl"; p.write_text("\n".join(["# TestMAX MBIST integration template", f"# read_netlist {{{netlist}}}", "# load_library dft_mbist.sldb", "# configure_memory_bist -controller <licensed_controller>", "# insert_memory_bist", "# write_netlist ./mbist_netlist.v", ""])); artifacts.append(str(p))
    if flow in ("dft", "lbist"):
        p = run_dir / "lbist.tcl"; p.write_text("\n".join(["# TestMAX LBIST integration template", f"# read_netlist {{{netlist}}}", "# load_library dft_lbist.sldb", "# configure_logic_bist -controller <licensed_controller>", "# insert_logic_bist", "# write_netlist ./lbist_netlist.v", ""])); artifacts.append(str(p))
    command_tool = "dc" if flow == "dft" else ("tmax" if flow == "atpg" else "dft")
    command_script = scan if flow == "dft" else (run_dir / "atpg_stuck_at.cmd" if flow == "atpg" else run_dir / f"{flow}.tcl")
    command = [executable(command_tool) or HOME_DEFAULTS[command_tool][1], "-f", str(command_script)]
    return command, command_script, artifacts

def adapter(flow, root, cfg, run_dir):
    top = discover_top(root, cfg.get("top"))
    sources = rtl_sources(root)
    fl = run_dir / "rtl.f"
    fl.write_text("\n".join(sources) + ("\n" if sources else ""))
    if flow in ("dft", "atpg", "mbist", "lbist"):
        command, script, artifacts = generate_dft_manager(root, cfg, run_dir, flow)
        return command, script
    if flow == "sim":
        tb = cfg.get("sim_tb", "sim/tb_top.sv")
        cmd = [executable("vcs") or "vcs", "-full64", "-sverilog", "-f", str(fl), tb, "-top", top, "-o", str(run_dir/"simv")]
        return cmd, None
    if flow == "debug":
        return [executable("verdi") or "verdi", "-sv", "-f", str(fl), "-top", top], None
    tcl_tool = {"synth":"dc", "lint":"spyglass", "cdc":"spyglass", "dft":"dft",
                "atpg":"tmax", "mbist":"dft", "lbist":"dft", "formal":"vcf",
                "formality":"formal"}.get(flow)
    if flow == "formal": tcl_tool = "vcf"
    if flow == "formality": tcl_tool = "formal"
    if not tcl_tool: tcl_tool = FLOW_TOOL.get(flow, "dc")
    script = run_dir / f"{flow}.tcl"
    lines = [tcl_header(flow), f"set TOP {top}", f"set ROOT {{{root}}}", f"set RUN {{{run_dir}}}"]
    lines += [f"set RTL_FILES [list {' '.join('{' + x + '}' for x in sources)}]"]
    if flow == "synth":
        lines += ["set_app_var search_path [list $ROOT $ROOT/rtl]", "read_verilog -rtl $RTL_FILES", "current_design $TOP", "link", "check_design", "compile_ultra", "write -format verilog -hierarchy -output $RUN/netlist.v", "write_sdc $RUN/constraints.sdc", "report_qor > $RUN/qor.rpt", "report_timing -max_paths 20 > $RUN/timing.rpt", "report_area > $RUN/area.rpt"]
        cmd = [executable("dc") or "dc_shell", "-f", str(script)]
    elif flow == "lint":
        lines += ["new_project -name eda_run -dir $RUN", "read_file -type verilog $RTL_FILES", "current_goal lint/lint_rtl", "run_goal"]
        cmd = [executable("spyglass") or "sg_shell", "-tcl", str(script)]
    elif flow == "cdc":
        lines += ["# CDC analysis is not implemented by this adapter.",
                  "puts {BLOCKED: configure a reviewed CDC script and waiver set before execution}"]
        cmd = [executable("spyglass") or "sg_shell", "-tcl", str(script)]
    elif flow == "formal":
        lines += ["read_verilog -r $RTL_FILES", "set_top $TOP", "check_fv_setup", "match", "verify", "report_fv -summary"]
        cmd = [executable("vcf") or "vc_static_shell", "-f", str(script)]
    elif flow == "formality":
        flow_cfg = cfg.get("flows", {}).get("formality", {})
        golden = flow_cfg.get("golden", [])
        revised = flow_cfg.get("revised", [])
        if isinstance(golden, str): golden = [golden]
        if isinstance(revised, str): revised = [revised]
        valid_lists = (isinstance(golden, list) and golden and all(isinstance(x, str) and x for x in golden) and
                       isinstance(revised, list) and revised and all(isinstance(x, str) and x for x in revised))
        if not valid_lists:
            lines += ["# BLOCKED: distinct flows.formality.golden and flows.formality.revised inputs are required.",
                      "puts {BLOCKED: golden and revised RTL were not configured}"]
        else:
            golden_paths = [resolve(root, x, must_exist=False) for x in golden]
            revised_paths = [resolve(root, x, must_exist=False) for x in revised]
            if any(not x.is_file() for x in golden_paths + revised_paths):
                lines += ["# BLOCKED: one or more configured Formality inputs are missing.",
                          "puts {BLOCKED: Golden and Revised source files must exist}"]
            else:
                same_paths = set(golden_paths) == set(revised_paths)
                same_content = (len(golden_paths) == len(revised_paths) and
                                sorted(sha256(x) for x in golden_paths) == sorted(sha256(x) for x in revised_paths))
                if same_paths or same_content:
                    lines += ["# BLOCKED: golden and revised source lists are identical.",
                              "puts {BLOCKED: Formality requires independent Golden and Revised inputs}"]
                else:
                    lines += ["read_verilog -golden [list " + " ".join("{" + str(x) + "}" for x in golden_paths) + "]",
                              "read_verilog -revised [list " + " ".join("{" + str(x) + "}" for x in revised_paths) + "]",
                              "set_top r:/WORK/$TOP", "match", "verify", "report_verification"]
        cmd = [executable("formal") or "fm_shell", "-f", str(script)]
    else:
        lines += ["puts {Adapter placeholder: provide project-specific Tcl in eda.yaml flows.*.script}"]
        cmd = [executable(tcl_tool) or tcl_tool, "-f", str(script)]
    script.write_text("\n".join(lines) + "\n")
    return cmd, script

def init_config(root, name=None, top=None, force=False):
    path = root / "eda.yaml"
    if path.exists() and not force:
        print(f"exists: {path} (use --force only if you intend to replace it)")
        return 2
    name = name or root.name
    top = top or "chip_top"
    available = [p for p in list(root.glob("rtl/**/*.sv")) + list(root.glob("rtl/**/*.v")) if p.is_file()]
    for src in available:
        try:
            m = re.search(r"\bmodule\s+([A-Za-z_][\w$]*)", src.read_text(errors="replace"))
            if m:
                top = m.group(1); break
        except OSError:
            pass
    rtl_patterns = ["rtl/**/*.sv" if any(p.suffix == ".sv" for p in available) else None,
                    "rtl/**/*.v" if any(p.suffix == ".v" for p in available) else None]
    rtl_patterns = [x for x in rtl_patterns if x] or ["rtl/**/*.sv"]
    path.write_text("\n".join([
        f"name: {name}", f"top: {top}", "rtl:", *("  - " + x for x in rtl_patterns),
        "filelists: []", "include_dirs: []", "defines: []", "pdk:",
        "  root: /path/to/pdk/TSMC28", "  target_library: path/to/slow.db",
        f"constraints: constraints/{name}.sdc", "flows:",
        "  sim: {simulator: vcs, tb: sim/tb_top.sv}",
        "  synth: {tool: dc, script: scripts/run_dc.tcl}",
        "  apr: {tool: icc2, script: scripts/run_icc2.tcl}",
        "  sta: {tool: pt, script: scripts/run_pt.tcl}", "dft:",
        "  enabled: false", "  scan: {chains: 1, compression: false}",
        "  mbist: {enabled: false, controller: vendor_ip}",
        "  lbist: {enabled: false, controller: vendor_ip}",
        "  atpg: {faults: [stuck_at, transition], tool: tmax}", ""
    ]))
    print(f"created: {path}")
    return 0

def main(argv=None):
    ap = argparse.ArgumentParser(prog="eda.py")
    ap.add_argument("command", choices=["init", "doctor", "plan", "run", "report", "validate", "resume"])
    ap.add_argument("--flow", choices=sorted(set(FLOW_TOOL) | {"rtl_to_sim", "rtl_to_regression", "rtl_to_synth", "rtl_to_synth_sta", "rtl_to_sim_synth"}))
    ap.add_argument("--tool", choices=sorted(HOME_DEFAULTS))
    ap.add_argument("--name")
    ap.add_argument("--top")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--run-id")
    ap.add_argument("--from", dest="start_stage")
    ap.add_argument("--to", dest="end_stage")
    ap.add_argument("--budget-seconds", type=float)
    ap.add_argument("--log-tail", nargs="?", const=50, type=int)
    args = ap.parse_args(argv)
    root = project_root()
    if args.command == "init":
        return init_config(root, args.name, args.top, args.force)
    if args.command == "resume" or (args.command == "report" and args.run_id):
        from flow_engine import main as flow_main
        forwarded = ["resume" if args.command == "resume" else "report", "--run-id", args.run_id or ""]
        if args.execute and args.command == "resume":
            forwarded.append("--execute")
        if args.start_stage:
            forwarded += ["--from", args.start_stage]
        if args.end_stage:
            forwarded += ["--to", args.end_stage]
        if args.budget_seconds is not None:
            forwarded += ["--budget-seconds", str(args.budget_seconds)]
        if args.log_tail is not None and args.command == "report":
            forwarded += ["--log-tail", str(args.log_tail)]
        return flow_main(forwarded)
    if args.command in ("plan", "run") and args.flow in {"rtl_to_sim", "rtl_to_regression", "rtl_to_synth", "rtl_to_synth_sta", "rtl_to_sim_synth"}:
        from flow_engine import main as flow_main
        forwarded = [args.command, "--flow", args.flow]
        if args.run_id:
            forwarded += ["--run-id", args.run_id]
        if args.start_stage:
            forwarded += ["--from", args.start_stage]
        if args.end_stage:
            forwarded += ["--to", args.end_stage]
        if args.budget_seconds is not None:
            forwarded += ["--budget-seconds", str(args.budget_seconds)]
        if args.command == "run" and args.execute and not args.dry_run:
            forwarded.append("--execute")
        return flow_main(forwarded)
    try:
        config_path = ensure_config(root)
        cfg = parse_config(config_path)
    except ConfigError as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}), file=sys.stderr)
        return 2
    if args.command in ("report", "validate"):
        report = parse_dft_reports(root)
        report["atpg"] = atpg_metrics(root)
        print(json.dumps(report, indent=2))
        return 0 if args.command == "report" or report["status"] == "pass" else 1
    if args.command == "doctor":
        checks = {}
        try:
            resolved = sources(root, cfg)
            checks["rtl_sources"] = len(resolved["rtl"])
        except ConfigError as exc:
            checks["rtl_error"] = str(exc)
        for flow in ("sim", "regression", "coverage", "synth", "sta"):
            if flow not in cfg.get("flows", {}):
                continue
            tool_name = FLOW_TOOL[flow]
            path = executable(tool_name)
            check = {"executable": path, "version": tool_version(path),
                     "status": "AVAILABLE" if path else "BLOCKED",
                     "license_status": "NOT_CHECKED"}
            try:
                with tempfile.TemporaryDirectory() as temp:
                    build_stages(flow, root, cfg, Path(temp), path)
                check["configuration_status"] = "PASS"
            except ConfigError as exc:
                check.update(status="BLOCKED", configuration_status="BLOCKED", error=str(exc))
            if flow in cfg.get("flows", {}):
                checks[flow] = check
        status = "BLOCKED" if "rtl_error" in checks or any(x.get("status") == "BLOCKED" for x in checks.values() if isinstance(x, dict)) else "PASS"
        try:
            runner = runner_config(cfg)
            runner_status = "PASS"
        except RunnerError as exc:
            runner, runner_status = {"kind": cfg.get("runner", {}).get("kind", "local")}, "BLOCKED"
            checks["runner_error"] = str(exc)
            status = "BLOCKED"
        print(json.dumps({"status": status, "project_root": str(root), "config": str(config_path),
                          "top": cfg["top"], "checks": checks,
                          "tools": {k: executable(k) for k in HOME_DEFAULTS},
                          "runner": {"configuration": runner, "configuration_status": runner_status},
                          "license_server_environment_set": bool(os.environ.get("LM_LICENSE_FILE") or os.environ.get("SNPSLMD_LICENSE_FILE")),
                          "note": "doctor validates local configuration and executable presence; license checkout is reported only by explicit feature probes or passing run evidence"}, indent=2))
        return 0 if status == "PASS" else 1
    if not args.flow: ap.error("--flow is required for plan/run")
    tool = args.tool or FLOW_TOOL[args.flow]; exe = executable(tool)
    run_id = args.run_id or dt.datetime.now().strftime("%Y%m%d-%H%M%S-%f") + "-" + args.flow
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", run_id):
        ap.error("--run-id must contain only letters, numbers, _, . or -")
    run_dir = root / "runs" / run_id
    if run_dir.exists():
        print(json.dumps({"status": "BLOCKED", "error": f"run already exists: {run_dir}"}), file=sys.stderr)
        return 2
    execute = args.command == "run" and args.execute and not args.dry_run
    if args.budget_seconds is not None and args.budget_seconds <= 0:
        ap.error("--budget-seconds must be positive")
    started = time.time()
    if execute and args.flow in EXECUTABLE_FLOWS and os.environ.get("EDA_REMOTE_EXECUTION") != "1":
        try:
            runner = runner_config(cfg)
            if runner.get("kind") == "ssh":
                result = execute_remote(root, cfg, args.flow, run_id, run_dir,
                                        start=args.start_stage, end=args.end_stage,
                                        budget_seconds=args.budget_seconds)
                print(json.dumps(result, indent=2))
                return 0 if result.get("status") == "PASS" else 1
        except RunnerError as exc:
            run_dir.mkdir(parents=True, exist_ok=True)
            result = {"run_id": run_id, "flow": args.flow, "status": "BLOCKED",
                      "error_class": "SSH_RUNNER_UNAVAILABLE", "reason": str(exc),
                      "runner": {"kind": "ssh"}}
            save(run_dir / "manifest.json", result)
            print(json.dumps(result, indent=2))
            return 1
    run_dir.mkdir(parents=True)
    if args.flow in EXECUTABLE_FLOWS:
        try:
            inputs, stages, options = build_stages(args.flow, root, cfg, run_dir, exe)
            cache_inputs = [config_path, *inputs.get("rtl", []), *inputs.get("filelists", []),
                            *inputs.get("include_dirs", []), Path(__file__).resolve(),
                            Path(__file__).with_name("eda_runtime.py"),
                            Path(__file__).with_name("eda_config.py"),
                            Path(__file__).with_name("stage_runtime.py"),
                            Path(__file__).with_name("flow_engine.py")]
            def gather_paths(value):
                if isinstance(value, dict):
                    for nested in value.values(): gather_paths(nested)
                elif isinstance(value, list):
                    for nested in value: gather_paths(nested)
                elif isinstance(value, str):
                    if not value.strip(): return
                    candidate = Path(value)
                    if not candidate.is_absolute(): candidate = root / candidate
                    if candidate.exists(): cache_inputs.append(candidate)
            gather_paths(options)
            pdk = cfg.get("pdk", {})
            if isinstance(pdk, dict):
                pdk_root = root / pdk.get("root", ".")
                for name in [pdk.get("target_library"), *pdk.get("link_libraries", [])]:
                    if name:
                        candidate = Path(name)
                        cache_inputs.append(candidate if candidate.is_absolute() else pdk_root / candidate)
            if cfg.get("constraints"):
                candidate = Path(cfg["constraints"])
                cache_inputs.append(candidate if candidate.is_absolute() else root / candidate)
            stage_project = project_contract(root, cfg, inputs, stages, cache_inputs)
            records = execute_plan(stages, run_dir, execute, root=root, run_id=run_id,
                                   project=stage_project, cache_inputs=cache_inputs,
                                   start=args.start_stage, end=args.end_stage,
                                   budget_seconds=args.budget_seconds if args.budget_seconds is not None else float("inf"))
            result = make_manifest(root, run_id, args.flow, tool, exe, inputs, stages, options, records, run_dir)
            result["project"] = cfg["name"]
            result["config"] = str(config_path)
            result["runner"] = {"kind": "local"}
            metrics = {}
            if args.flow in ("synth", "sta"):
                report_paths = [run_dir / "qor.rpt", run_dir / "area.rpt", run_dir / "timing.rpt", run_dir / "constraints.rpt"]
                result["qor"] = parse_qor(report_paths)
                metrics.update(result["qor"])
                if args.flow == "synth":
                    result["power"] = parse_power(run_dir / "power.rpt")
                    result["power"]["provenance"] = options.get("power_provenance")
                    result["power"]["activity_file"] = options.get("activity_file")
                    metrics["power"] = result["power"]
                required_metrics = ("area", "wns", "tns") if args.flow == "synth" else ("wns", "tns")
                if execute and any(result["qor"].get(key) is None for key in required_metrics):
                    result["status"] = "BLOCKED"
                    result["error_class"] = "METRIC_MISSING"
                    result["reason"] = "required QoR metrics could not be parsed from reports"
                if execute and args.flow == "synth" and options.get("activity_file") and not any(
                        result["power"].get(key) is not None for key in ("total_dynamic_power", "cell_leakage_power", "total_power")):
                    result["status"] = "BLOCKED"
                    result["error_class"] = "METRIC_MISSING"
                    result["reason"] = "SAIF was configured but DC power metrics could not be parsed"
            if args.flow in ("sim", "regression"):
                coverage_record = next((item for item in records if item.get("name") == "coverage_summary"), None)
                if coverage_record and coverage_record.get("metrics"):
                    result["coverage"] = coverage_record["metrics"]
                    metrics["coverage"] = result["coverage"]
                test_results = [item for item in records if item.get("kind") == "simulation_result" or item.get("test_name") is not None and item.get("name", "").startswith("result_")]
                if test_results:
                    metrics["regression"] = {"tests_total": len(test_results),
                                              "tests_passed": sum(1 for item in test_results if item.get("status") == "PASS"),
                                              "tests_failed": sum(1 for item in test_results if item.get("status") == "FAIL"),
                                              "seeds": [item.get("seed") for item in test_results]}
            result["metrics"] = metrics
            result["efficiency"] = {"workflow_elapsed_sec": round(time.time() - started, 6),
                                    "eda_stage_elapsed_sec": round(sum(x.get("elapsed_sec", 0) for x in records), 6),
                                    "stage_count": sum(1 for x in records if x.get("status") != "NOT_RUN"),
                                    "tool_invocations": sum(1 for x in records if x.get("return_code") is not None and not x.get("cache_hit") and not x.get("checkpoint_reuse")),
                                    "cache_hits": sum(1 for x in records if x.get("cache_hit")),
                                    "checkpoint_reuses": sum(1 for x in records if x.get("checkpoint_reuse")),
                                    "agent_invocations": None,
                                    "token_usage": None}
            metrics_path = run_dir / "metrics.json"
            save(metrics_path, {"schema_version": 1, "run_id": run_id, "flow": args.flow,
                                "status": result["status"], "metrics": metrics,
                                "tool_versions": result.get("tool_versions", {}),
                                "source_revision": result.get("source_revision")})
            result.setdefault("artifacts", []).append(artifact_record(metrics_path))
        except ConfigError as exc:
            result = {"run_id": run_id, "flow": args.flow, "status": "BLOCKED",
                      "error_class": "CONFIG_INVALID", "error": str(exc)}
        save(run_dir / "manifest.json", result)
        save(run_dir / "checkpoint.json", {"schema_version": 2, "run_id": run_id,
             "project": cfg.get("name", root.name), "flow": args.flow, "status": result["status"],
             "stages": result.get("stages", []), "manifest": str(run_dir / "manifest.json"),
             "budget_seconds": args.budget_seconds,
             "budget_charged_seconds": round(_attempts_charged(run_dir / "attempts.jsonl"), 6),
             "updated_at": time.time()})
        print(json.dumps(result, indent=2))
        return 0 if not (args.command == "run" and args.execute and not args.dry_run) or result["status"] == "PASS" else 1
    if args.flow in SCRIPT_ONLY_FLOWS:
        command, script = adapter(args.flow, root, cfg, run_dir)
        support = "template" if args.flow in TEMPLATE_ONLY else "planning_only"
        execute = args.command == "run" and args.execute and not args.dry_run
        result = {"run_id": run_id, "flow": args.flow, "status": "BLOCKED" if execute else "NOT_RUN",
                  "tool": tool, "support": support, "command": command,
                  "generated_script": str(script) if script else None,
                  "reason": "no validated executable adapter is available for this flow" if execute else None,
                  "error_class": "ADAPTER_UNSUPPORTED" if execute else None,
                  "environment": {"license_server_environment_set": bool(os.environ.get("LM_LICENSE_FILE") or os.environ.get("SNPSLMD_LICENSE_FILE"))}}
        save(run_dir / "manifest.json", result)
        print(json.dumps(result, indent=2))
        return 1 if execute else 0

if __name__ == "__main__": sys.exit(main())
